package Entity.enums;

/**
 * Product category used to classify physical-goods advertisements.
 * Enables category-based filtering and browsing on the platform.
 */
public enum Category {

    /** Consumer and industrial electronic devices. */
    ELECTRONICS,

    /** Cars, motorcycles, and other vehicles. */
    VEHICLE,

    /** Household furniture and interior decoration items. */
    FURNITURE,

    /** Books, magazines, and educational materials. */
    BOOKS,

    /** Apparel, footwear, and accessories. */
    CLOTHING,

    /** Apartments, houses, land, and commercial spaces. */
    REAL_ESTATE,

    /** Sports equipment, fitness gear, and outdoor items. */
    SPORTS,

    /** Children's toys and games. */
    TOYS,

    /** Items that do not fit any of the other defined categories. */
    OTHER
}
