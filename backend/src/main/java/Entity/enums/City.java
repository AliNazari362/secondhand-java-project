package Entity.enums;

/**
 * Iranian cities supported as advertisement locations.
 * Used to enable location-based search and filtering.
 */
public enum City {

    /** Tehran – capital and largest city of Iran. */
    TEHRAN,

    /** Isfahan – major cultural and industrial city. */
    ISFAHAN,

    /** Shiraz – known for history and tourism. */
    SHIRAZ,

    /** Mashhad – largest city in northeastern Iran. */
    MASHHAD,

    /** Tabriz – major city in northwestern Iran. */
    TABRIZ,

    /** Ahvaz – capital of Khuzestan province. */
    AHVAZ,

    /** Kerman – capital of Kerman province. */
    KERMAN,

    /** Rasht – capital of Gilan province. */
    RASHT,

    /** Yazd – historic city in central Iran. */
    YAZD,

    /** Qom – religious and political centre. */
    QOM,

    /** Karaj – large city west of Tehran. */
    KARAJ,

    /** Any city not explicitly listed above. */
    OTHER
}
